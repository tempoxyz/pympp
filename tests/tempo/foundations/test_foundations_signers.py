"""Native multisig envelopes vs ox 0.14.45 / viem 2.57.1 vectors.

Vectors: ``fixtures/ox_vectors_3.json``, generated by ``fixtures/generate_ox_vectors_3.mjs``.
"""

from __future__ import annotations

import json
from dataclasses import replace
from pathlib import Path

import pytest

from mpp.tempo._internal import signature as sig
from mpp.tempo._internal.hexutil import rlp_encode, to_bytes

V = json.loads((Path(__file__).parent / "fixtures/ox_vectors_3.json").read_text())


class TestMultisigEnvelope:
    @pytest.mark.parametrize("name", ["multisig", "multisigCurrent"])
    def test_roundtrips_ox_serialization(self, name: str) -> None:
        envelope = sig.deserialize(V[name]["envelope"])
        assert isinstance(envelope, sig.MultisigSignature)
        assert sig.serialize(envelope) == V[name]["envelope"]

    def test_rpc_is_the_payload_without_the_type_byte(self) -> None:
        envelope = sig.deserialize(V["multisig"]["envelope"])
        assert sig.to_rpc(envelope) == V["multisig"]["rpc"]

    def test_extract_address_is_the_multisig_account(self) -> None:
        envelope = sig.deserialize(V["multisig"]["envelope"])
        assert sig.extract_address(envelope, b"\x00" * 32) == V["multisig"]["account"]
        with pytest.raises(sig.InvalidSignatureEnvelopeError, match='type "multisig"'):
            sig.verify(envelope, payload=b"\x00" * 32, address=V["multisig"]["account"])

    def test_current_config_carries_salt_version_and_p256_approval(self) -> None:
        envelope = sig.deserialize(V["multisigCurrent"]["envelope"])
        assert isinstance(envelope, sig.MultisigSignature)
        assert envelope.config.version == 3
        assert envelope.config.salt == "0x" + "aa" * 32
        (approval,) = envelope.signatures
        assert isinstance(approval, sig.P256Signature)
        assert sig.verify(
            approval,
            payload=to_bytes(V["multisigCurrent"]["digest"]),
            address=sig.p256_address(approval.public_key_x, approval.public_key_y),
        )

    def test_keychain_approvals_are_rejected(self) -> None:
        envelope = sig.deserialize(V["multisig"]["envelope"])
        assert isinstance(envelope, sig.MultisigSignature)
        keychain = sig.KeychainEnvelope(user_address="0x" + "cd" * 20, inner=envelope.signatures[0])
        payload = rlp_encode(
            [
                to_bytes(envelope.account),
                sig.multisig_config_to_tuple(envelope.config),
                [keychain.to_bytes()],
            ]
        )
        with pytest.raises(sig.InvalidSignatureEnvelopeError, match="must be primitive"):
            sig.deserialize(b"\x05" + payload)

    def test_initial_account_cannot_be_an_owner(self) -> None:
        envelope = sig.deserialize(V["multisig"]["envelope"])
        assert isinstance(envelope, sig.MultisigSignature)
        with pytest.raises(sig.InvalidMultisigApprovalError, match="cannot be an owner"):
            sig.serialize(replace(envelope, account=envelope.config.owners[0].owner))

    def test_non_canonical_config_tuple_is_rejected(self) -> None:
        with pytest.raises(sig.InvalidMultisigConfigError, match="invalid config RLP tuple"):
            sig.multisig_config_from_tuple([b"\x00" * 32, b"\x00", b"\x01", []])
